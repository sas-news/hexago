"""Train the 28 -> 64 -> 32 -> 8 MLP on the cached synthetic dataset.

Data is pre-generated by build_cache.py (feature matrices in cache/{train,val,test}.npz).
Feature standardisation is folded into the first layer so js/photo/model.js can
consume raw features.

Usage:
  python train.py [--epochs 40] [--batch 256] [--lr 1e-3] [--out cache/model.npz]
"""
import argparse
import json
import os
import time

import numpy as np

import mlp

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, 'cache')


def load_split(split):
    path = os.path.join(CACHE, split + '.npz')
    if not os.path.exists(path):
        raise SystemExit('missing cache: %s (run build_cache.py --split %s)' % (path, split))
    d = np.load(path, allow_pickle=False)
    return d['X'].astype(np.float32), d['y'].astype(np.int64)


def evaluate(params, X, y, label=''):
    probs = mlp.predict_proba(params, X)
    pred = probs.argmax(axis=1)
    acc = float((pred == y).mean())
    cm = mlp.confusion(y, pred)
    print('%-12s accuracy %.5f  (%d/%d)' % (label, acc, int((pred == y).sum()), len(y)))
    lines = []
    for c in range(8):
        tot = cm[c].sum()
        if tot:
            lines.append('%s %.1f%% (n=%d)' % (mlp.CLASSES[c], 100.0 * cm[c, c] / tot, tot))
    print('    ' + '  '.join(lines))
    return acc, cm, pred, probs


def train(params, X, y, Xv, yv, epochs, batch, lr, seed=0, quiet=False):
    rng = np.random.default_rng(seed)
    n = len(X)
    best = (-1.0, None, 0)
    m = []
    v = []
    for p in params:
        m.extend([np.zeros_like(p['W']), np.zeros_like(p['b'])])
        v.extend([np.zeros_like(p['W']), np.zeros_like(p['b'])])
    B1, B2 = 0.9, 0.999
    eps = 1e-8
    step = 0
    for ep in range(epochs):
        idx = rng.permutation(n)
        t0 = time.time()
        tot_loss = 0.0
        for i in range(0, n, batch):
            bi = idx[i:i + batch]
            xb = X[bi]
            yb = y[bi]
            nb = len(bi)
            # --- forward ---
            acts = [xb.astype(np.float64)]
            zs = []
            a = acts[0]
            for li, p in enumerate(params):
                z = a @ p['W'].astype(np.float64).T + p['b'].astype(np.float64)
                zs.append(z)
                if li < len(params) - 1:
                    a = np.maximum(z, 0.0)
                else:
                    a = z
                acts.append(a)
            logits = acts[-1]
            logits = logits - logits.max(axis=1, keepdims=True)
            e = np.exp(logits)
            probs = e / e.sum(axis=1, keepdims=True)
            loss = -np.log(np.maximum(probs[np.arange(nb), yb], 1e-12)).mean()
            tot_loss += loss * nb
            # --- backward ---
            g = probs.copy()
            g[np.arange(nb), yb] -= 1.0
            g /= nb
            grads = [None] * len(params)
            for li in range(len(params) - 1, -1, -1):
                W = params[li]['W'].astype(np.float64)
                dW = g.T @ acts[li]
                db = g.sum(axis=0)
                grads[li] = {'W': dW, 'b': db}
                if li > 0:
                    g = (g @ W) * (zs[li - 1] > 0)
            # --- adam ---
            step += 1
            for li in range(len(params)):
                for key in ('W', 'b'):
                    gr = grads[li][key]
                    idx_m = li * 2 + (0 if key == 'W' else 1)
                    m[idx_m] = B1 * m[idx_m] + (1 - B1) * gr
                    v[idx_m] = B2 * v[idx_m] + (1 - B2) * (gr * gr)
                    mh = m[idx_m] / (1 - B1 ** step)
                    vh = v[idx_m] / (1 - B2 ** step)
                    params[li][key] = (params[li][key] - lr * mh / (np.sqrt(vh) + eps)).astype(np.float32)
        # validation
        probs_v = mlp.predict_proba(params, Xv)
        vacc = float((probs_v.argmax(axis=1) == yv).mean())
        if not quiet:
            print('epoch %2d  loss %.4f  val_acc %.5f  (%.1fs)'
                  % (ep + 1, tot_loss / n, vacc, time.time() - t0), flush=True)
        if vacc > best[0]:
            best = (vacc, [{'W': p['W'].copy(), 'b': p['b'].copy()} for p in params], ep + 1)
    print('best val_acc %.5f at epoch %d' % (best[0], best[2]))
    return best[1], best[0]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--epochs', type=int, default=40)
    ap.add_argument('--batch', type=int, default=256)
    ap.add_argument('--lr', type=float, default=1e-3)
    ap.add_argument('--seed', type=int, default=42)
    ap.add_argument('--out', default=os.path.join(CACHE, 'model.npz'))
    ap.add_argument('--max-train', type=int, default=0, help='limit training samples (debug)')
    args = ap.parse_args()

    X, y = load_split('train')
    Xv, yv = load_split('val')
    if args.max_train:
        X, y = X[:args.max_train], y[:args.max_train]
    print('train %s  val %s' % (X.shape, Xv.shape))
    print('class counts train:', np.bincount(y, minlength=8).tolist())

    # standardise by train statistics (folded into layer 1 later)
    mu = X.mean(axis=0)
    sd = X.std(axis=0) + 1e-6
    Xn = (X - mu) / sd
    Xvn = (Xv - mu) / sd

    rng = np.random.default_rng(args.seed)
    params = mlp.init_params(rng, (28, 64, 32, 8))
    params, best = train(params, Xn, y, Xvn, yv, args.epochs, args.batch, args.lr,
                         seed=args.seed)

    # fold standardisation into the first layer:  z = W1 (x - mu)/sd + b1
    mlp.fold_standardisation(params, mu, sd)

    print('\n== evaluation ==')
    evaluate(params, X, y, 'train')
    evaluate(params, Xv, yv, 'val')
    for split in ('test',):
        p = os.path.join(CACHE, split + '.npz')
        if os.path.exists(p):
            Xt, yt = load_split(split)
            evaluate(params, Xt, yt, split)

    # per-scenario breakdown on test cache
    p = os.path.join(CACHE, 'test.npz')
    if os.path.exists(p):
        d = np.load(p, allow_pickle=False)
        Xt, yt = d['X'].astype(np.float32), d['y'].astype(np.int64)
        pred = mlp.predict(params, Xt)
        print('\n== test by scenario (lighting/material/theme) ==')
        stats = {}
        if 'board' in d:
            boards = d['board']
            metas = d['meta']
            for bi in np.unique(boards):
                m = boards == bi
                parts = str(metas[bi]).split("'")
                sk = '%s/%s/%s' % (parts[3], parts[5], parts[1])
                s = stats.setdefault(sk, [0, 0])
                s[0] += int((pred[m] == yt[m]).sum())
                s[1] += int(m.sum())
        for k in sorted(stats):
            ok, tot = stats[k]
            print('  %-40s %.4f  (%d/%d)' % (k, ok / tot, ok, tot))

    np.savez(args.out, **{'W%d' % i: p['W'] for i, p in enumerate(params)},
             **{'b%d' % i: p['b'] for i, p in enumerate(params)})
    print('\nsaved %s' % args.out)

    # real photo patches produced by the browser pipeline (Lead)
    rjson = os.path.normpath(os.path.join(HERE, '../testdata/IMG_0252.patches.json'))
    if os.path.exists(rjson):
        import json as _json
        import features as _F
        d = _json.load(open(rjson))
        P = np.asarray(d['patches'], np.float64).reshape(-1, 16, 16, 3)
        baseline = np.asarray(d['baseline'], np.float64)
        Xr = np.stack([_F.extract_features(p, baseline) for p in P])
        yr = np.array([mlp.CLASSES.index(l) for l in d['labels']], dtype=np.int64)
        probs = mlp.predict_proba(params, Xr)
        pred = probs.argmax(axis=1)
        cm = mlp.confusion(yr, pred)
        print('\n== REAL PHOTO PATCHES (browser pipeline) ==')
        print('accuracy %.5f  errors %d / %d' % (float((pred == yr).mean()),
                                                  int((pred != yr).sum()), len(yr)))
        print('per-class:', {mlp.CLASSES[c]: (round(100.0 * cm[c, c] / cm[c].sum(), 1)
                                             if cm[c].sum() else None) for c in range(8)})
        for i in np.where(pred != yr)[0]:
            print('  patch %3d true %-6s pred %-6s conf %.3f' %
                  (i, mlp.CLASSES[yr[i]], mlp.CLASSES[pred[i]], probs[i].max()))

    # real photo (own canonicalisation of IMG_0252) if available
    rp = os.path.join(CACHE, 'real_v2.npz')
    if os.path.exists(rp):
        r = np.load(rp)
        Xr, yr = r['X'], r['y']
        probs = mlp.predict_proba(params, Xr)
        pred = probs.argmax(axis=1)
        acc = float((pred == yr).mean())
        cm = mlp.confusion(yr, pred)
        print('\n== REAL PHOTO IMG_0252 (own canonicalisation) ==')
        print('accuracy %.5f  errors %d / %d' % (acc, int((pred != yr).sum()), len(yr)))
        print('per-class:', {mlp.CLASSES[c]: (round(100.0 * cm[c, c] / cm[c].sum(), 1)
                                             if cm[c].sum() else None) for c in range(8)})
        bad = np.where(pred != yr)[0]
        for i in bad:
            print('  point %3d  true %-6s pred %-6s conf %.3f  probs %s'
                  % (i, mlp.CLASSES[yr[i]], mlp.CLASSES[pred[i]], probs[i].max(),
                     np.round(probs[i], 2).tolist()))


if __name__ == '__main__':
    main()
